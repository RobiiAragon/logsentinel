"""Generate a Hugging Face-style model card (MODEL_CARD.md) from the committed artifacts.

Every number comes from ``models/cards.json``, ``models/train_report.json`` and an
``evaluate --out`` result file, so the card can be regenerated (and checked in CI)
instead of being edited by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

DESCRIPTIONS = {
    "iforest": "Isolation Forest (100 trees, scikit-learn, exported with skl2onnx)",
    "autoencoder": "Autoencoder 44-32-8-32-44, FP32, preprocessing and score inside the graph",
    "autoencoder-int8": "Same autoencoder, static QDQ W8A8 (int8 weights, uint8 activations)",
    "autoencoder-w8a16": "Same autoencoder, static QDQ W8A16 (int8 weights, uint16 activations)",
}


def _f(v: float, d: int = 3) -> str:
    return f"{v:.{d}f}"


def render(models_dir: Path, results_path: Path) -> str:
    cards = json.loads((models_dir / "cards.json").read_text(encoding="utf-8"))
    train = json.loads((models_dir / "train_report.json").read_text(encoding="utf-8"))
    res = json.loads(results_path.read_text(encoding="utf-8"))
    dev = res.get("device", {})
    rows = {(r["model"], r["provider"]): r for r in res["results"]}
    providers = sorted({r["provider"] for r in res["results"]}, key=lambda p: p != "cpu")
    cpu = providers[0]
    models = [m["name"] for m in cards["models"]]

    front = [
        "---",
        "license: mit",
        "library_name: onnx",
        "pipeline_tag: tabular-classification",
        "tags: [anomaly-detection, log-analysis, onnx, int8, quantization, hdfs, soc]",
        "datasets: [loghub/HDFS_v1]",
        "model-index:",
    ]
    for name in models:
        r = rows.get((name, cpu))
        if not r:
            continue
        front += [
            f"- name: logsentinel-{name}",
            "  results:",
            "  - task: {type: anomaly-detection, name: Log session anomaly detection}",
            "    dataset: {name: Loghub HDFS_v1 (chronological test split), type: loghub/HDFS_v1}",
            "    metrics:",
        ]
        for key in ("precision", "recall", "f1", "pr_auc", "roc_auc"):
            front.append(f"    - {{type: {key}, value: {r[key]:.4f}}}")
    front.append("---")

    os_name = "macOS" if dev.get("os") == "Darwin" else dev.get("os", "")
    who = f"{dev.get('cpu', '?')}, {os_name} {dev.get('os_version', '')}".strip()
    out = [
        *front,
        "",
        "# LogSentinel detectors",
        "",
        "Unsupervised / one-class detectors that flag anomalous HDFS block sessions from",
        "event-template count vectors. Generated by `logsentinel card` from the committed",
        "artifacts; do not edit by hand.",
        "",
        "## Models",
        "",
        "| Name | File | What it is | Trained on | Alert threshold | Validation F1 |",
        "|---|---|---|---|---:|---:|",
    ]
    for m in cards["models"]:
        out.append(
            f"| `{m['name']}` | `{m['file']}` | {DESCRIPTIONS.get(m['name'], '')} | "
            f"{m['trained_on']} | {m['threshold']:.4f} | {_f(m['val_f1'])} |"
        )
    t = next(iter(res["results"]))
    out += [
        "",
        f"## Evaluation (test split, measured on {who})",
        "",
        f"Test split: {t['n']:,} sessions, {t['positives']:,} anomalous. Thresholds were chosen",
        "on the validation split and applied unchanged. Source:",
        f"`{results_path.as_posix()}` (created {res.get('created', '?')}, onnxruntime",
        f"{dev.get('onnxruntime', '?')}).",
        "",
        "| Model | Precision | Recall | F1 | PR-AUC | ROC-AUC | TP / FP / FN | Size (KB) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name in models:
        r = rows.get((name, cpu))
        if r:
            out.append(
                f"| `{name}` | {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | "
                f"{_f(r['pr_auc'])} | {_f(r['roc_auc'])} | {r['tp']} / {r['fp']} / {r['fn']} | "
                f"{r['size_kb']:.1f} |"
            )
    out += [
        "",
        "Speed per execution provider (batch 1 latency over 300 calls; throughput over the",
        "whole test split in batches of 4096):",
        "",
        "| Model | EP | p50 (ms) | p99 (ms) | Sessions/s |",
        "|---|---|---:|---:|---:|",
    ]
    for name in models:
        for p in providers:
            r = rows.get((name, p))
            if r:
                out.append(
                    f"| `{name}` | {p} | {r['p50_ms']:.4f} | {r['p99_ms']:.4f} | "
                    f"{r['sessions_per_s']:,.0f} |"
                )
    ref = train.get("test_reference", {})
    if ref:
        out += [
            "",
            "Reference points on the same test split (not exported):",
            "",
            "| Model | Precision | Recall | F1 | PR-AUC |",
            "|---|---:|---:|---:|---:|",
        ]
        for name, r in ref.items():
            out.append(
                f"| {name} | {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | "
                f"{_f(r['pr_auc'])} |"
            )
    out += [
        "",
        "## Training data and labels",
        "",
        f"- Dataset: {cards.get('dataset', 'Loghub HDFS_v1')} (CC BY 4.0), split "
        f"{cards.get('split', '')}.",
        "- `iforest` and `autoencoder-unsupervised` use no labels at all.",
        "- `autoencoder` and its quantized variants are **one-class** models: they are fit only",
        "  on train-period blocks whose ground-truth label is *Normal*. That uses the training",
        "  labels to remove anomalies (in production: a baseline period an operator vetted as",
        "  healthy). Inference needs no labels.",
        "- Thresholds use validation labels (best F1).",
        "",
        "## Intended use and limitations",
        "",
        "- Triage aid for HDFS-style logs that carry a session id (block id). Other log",
        "  sources need their own templates, sessions and thresholds.",
        "- Templates were mined on the training period; unseen events map to one",
        "  `<UNKNOWN TEMPLATE>` feature, so a new but harmless log line can raise scores.",
        "- HDFS_v1 is from 2008; anomaly rates and failure modes in a modern cluster differ.",
        "  Re-pick the threshold (`logsentinel detect --threshold`) on your own validation data.",
        "- Not a security control on its own; alerts need analyst review.",
        "",
    ]
    return "\n".join(out)


def write(models_dir: Path, results_path: Path, out: Path) -> Path:
    out.write_text(render(models_dir, results_path), encoding="utf-8")
    return out
